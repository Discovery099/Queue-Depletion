"""Export Pine v6 strategies for every evaluated genome with a win rate of 50% or more (owner request).

None of these is certified: every one failed a gate.  The figures in each file's header are stage 1
SCREENING results on the three walk-forward test folds of the genome's island (the folds the search
selects on), so they flatter.  Research data only.

Outputs under deliverables/:
  SEH_strategies_best.zip          curated: closest to passing, held up on unseen data, best per timeframe
  all_50pct/SEH_all_<part>.zip     every distinct strategy with win rate >= 50% and at least 30 trades
  SEH_INDEX_all_50pct.csv.gz       one row per strategy (including duplicates and the ones that cannot be exported)
"""
import collections
import csv
import glob
import gzip
import io
import json
import os
import sqlite3
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from audit import canary, static_audit  # noqa: E402
from engine import path, read_json  # noqa: E402
from genome import compile_pine, genome as GN  # noqa: E402
from orchestrator import evaluate as EV  # noqa: E402

canary.install()
MIN_TRADES = 30
YEARS_HOME = len(EV.fold_sessions(EV.ISLAND_FOLDS["A"])) / 252.0
YEARS_ALL = len(EV.fold_sessions(EV.TEST_FOLDS)) / 252.0
OUT = path("deliverables")

README = """# Strategy scripts with a win rate of 50% or more

Every file is a complete, self-contained Pine v6 strategy that you can paste into TradingView and backtest.

## Read this first

- **None of these strategies is certified.** Every one failed at least one gate of the research harness. The run of 100,000
  generations ended with no strategy reaching even the lowest tier.
- **A win rate of 50% or more does not mean profitable.** {unprofitable} of the {total} strategies in the complete set lost money
  even on the data they were screened on. Each file's header and the index give the profit factor.
- **The header figures flatter.** They are screening results on three walk-forward test folds of the research data (about 355
  sessions, ES and YM pooled, 1 contract, $1.25 commission per side, 1 tick slippage). The search chose strategies on those same
  folds. On data that never influenced them, the leading strategies kept about 70% wins but their profit factor fell to about 1.27.
- **TradingView will not match the research engine exactly.** The research engine assumes the stop fills before the target when
  both fall inside one bar and requires price to trade through a target by one tick; TradingView is more optimistic. Its continuous
  contract can also differ slightly from the research data. Expect TradingView's win rate and profit to look somewhat better.
- Nothing here is financial advice, and no backtest is a promise of live performance.

## How to backtest one

1. Open a chart of **ES1!** or **YM1!** with **regular trading hours only** (09:30 to 16:00 Eastern). The scripts' session logic
   needs a regular-hours chart.
2. Set the chart to the timeframe in the file name (`5min`, `10min`, `15min`, `30min` or `60min`).
3. Open the Pine Editor, paste the file, click "Add to chart", then open the Strategy Tester.
4. Leave the inputs at their defaults. Execution mode stays `Sim/Paper`; no webhook URL is embedded and nothing is sent anywhere.
5. Quantity defaults to 4 contracts (as in your original script); the research figures are for 1 contract. Win rate and profit
   factor do not depend on quantity.
6. A few strategies read the other index future. They have an input "Companion instrument": set it to ES1! when the chart is YM,
   and to YM1! when the chart is ES.
7. To compare with the research figures, restrict the Strategy Tester to dates up to 2024-04-29 (the research period). Dates after
   that were never used and are your own out-of-sample test.

## What is in this archive

{contents}

File names: `g<generation>_<timeframe>_wr<win rate %>_pf<profit factor>_n<trades>.pine`. `SEH_INDEX.csv` lists every file with its
figures and a one-line description of its rules; sort it in a spreadsheet to choose what to test.

Index columns: `win_rate`, `twin_win_rate` (what random entries with the same exits win: the part of the win rate that comes
from the exits alone), `alpha_pts` (win rate minus twin: the part that comes from the entries; before generation 2,001 this is
overstated for some strategies), `profit_factor`, `trades` (on the screening folds, both instruments), `trades_per_year` (per
instrument), `score` (the harness's composite robustness score), `status`.

## How the scripts were checked

Each script was generated by the same compiler from the strategy's rules. The compiler's output was verified against the research
engine by an independent interpreter for every one of the 196 techniques and for eight complete strategies; the individual files
here were not each re-verified. Every file passed the static audit for repainting and lookahead constructs.
"""


def one_line(g):
    s = g["slots"]
    f = lambda e: e["atom"] + ("[inv]" if e.get("inv") else "") + "(" + ",".join(f"{k}={v}" for k, v in e["params"].items()) + ")"  # noqa: E731
    ctx = [f(e) for k in ("regime", "location", "filter") for e in s[k]]
    t = (" " + s["trigger"]["combine"] + " ").join(f(e) for e in s["trigger"]["atoms"])
    ens = "".join(" || " + " ".join(f(e) for e in m["trigger"]["atoms"]) for m in g.get("ensemble", []))
    ent = s["entry"]["type"] if s["entry"]["type"] == "market" else f"{s['entry']['type']}@{s['entry']['offset_atr']}ATR"
    return f"{t}{ens}" + (f" WITH {'; '.join(ctx)}" if ctx else "") + f" | stop {f(s['risk']['stop'])} | exit {'; '.join(f(e) for e in s['exit'])} | {ent}"


def statement(r, extra=""):
    twin = r["wr"] - r["alpha"] / 100.0
    return (f"NOT CERTIFIED. This strategy failed the research harness's gates ({r['status']}). Exported for your own backtesting only.\n"
            f"USE A {r['tf']}-MINUTE CHART, regular trading hours (09:30-16:00 Eastern), ES1! or YM1!.\n\n"
            f"SCREENING RESULT (research walk-forward test folds of island {r['island']}, ES and YM pooled, 1 contract, base costs)\n"
            f"Win rate (net, flat-to-flat):                 {100 * r['wr']:.1f} %   (n = {r['n']} trades)\n"
            f"Geometry baseline (random-entry twin median): {100 * twin:.1f} %\n"
            f"Win-rate alpha:                               {r['alpha']:+.1f} points\n"
            f"Profit factor:                                {r['pf']:.2f}\n"
            f"Trades per year per instrument:               {r['n'] / 2 / YEARS_HOME:.0f}\n"
            "These are screening figures on the folds the search selected on; they flatter. See README.md." + extra)


def main():
    os.makedirs(os.path.join(OUT, "all_50pct"), exist_ok=True)
    db = sqlite3.connect("file:" + path("ledger/lineage.sqlite") + "?mode=ro", uri=True)
    rows = []
    for gen, isl, tf, cx, status, score, n, wr, pf, alpha, js in db.execute(
            "SELECT generation, island, tf, complexity, status, score, n_trades, win_rate, pf, alpha, genome FROM genomes "
            "WHERE win_rate >= 0.5 AND n_trades >= 1 ORDER BY generation"):
        rows.append({"gen": gen, "island": isl, "tf": tf, "cx": cx, "status": status, "score": score or 0.0, "n": n, "wr": wr, "pf": pf or 0.0,
                     "alpha": alpha or 0.0, "js": js})
    fd = read_json(path("reports/final_data.json"))
    six = {h["generation"]: h for h in fd["home_only"]}
    surv = {}
    for f in sorted(glob.glob(path("reports", "exchange_*.json"))):
        for x in read_json(f)["rows"]:
            if x.get("survived"):
                surv[x["generation"]] = x
    seen, index = {}, []
    can = set(canary.canary_ids())
    exportable = []
    for r in rows:
        g = json.loads(r["js"])
        r["g"] = g
        key = (r["island"], r["tf"], r["n"], round(r["wr"], 6), round(r["pf"], 6))
        note = ""
        if r["n"] < MIN_TRADES:
            note = f"not exported: fewer than {MIN_TRADES} trades"
        elif any(e["atom"] in can for e in GN.atom_entries(g)):
            note = "not exported: uses a canary (a no-information control series that exists only inside the research harness)"
        elif key in seen:
            note = f"not exported: identical trades to generation {seen[key]}"
        else:
            seen[key] = r["gen"]
            exportable.append(r)
        r["note"] = note
    # ---- tiers for the curated archive
    tier = {}
    for r in exportable:
        if r["gen"] in six:
            tier[r["gen"]] = "01_closest_to_passing"
        elif r["gen"] in surv:
            tier[r["gen"]] = "02_held_up_on_unseen_data"
    for tf in (5, 10, 15, 30, 60):
        c = [r for r in exportable if r["tf"] == tf and r["gen"] > 20008 and r["pf"] > 1.0 and r["n"] >= 150 and r["gen"] not in tier]
        for r in sorted(c, key=lambda r: -r["score"])[:150]:
            tier[r["gen"]] = f"03_best_by_score_{tf:02d}min"
    # ---- write archives
    parts = collections.OrderedDict()

    def part_of(r):
        if r["tf"] != 5:
            return f"{r['tf']:02d}min"
        return "05min_wr50-60" if r["wr"] < 0.60 else "05min_wr60-65" if r["wr"] < 0.65 else "05min_wr65-70" if r["wr"] < 0.70 else "05min_wr70plus"

    best = zipfile.ZipFile(os.path.join(OUT, "SEH_strategies_best.zip"), "w", zipfile.ZIP_DEFLATED, compresslevel=9)
    zips, counts, failed, audit_hits, best_rows = {}, collections.Counter(), 0, 0, []
    for r in exportable:
        g = r["g"]
        extra = ""
        if r["gen"] in six:
            h = six[r["gen"]]
            extra = (f"\n\nON ALL SIX TEST FOLDS (it passed the screen on its island's folds, then failed here): win rate {100 * h['win_rate']:.1f}% "
                     f"(n = {h['n']}), twin {100 * h['twin']:.1f}%, alpha {h['alpha']:+.1f}, profit factor {h['profit_factor']:.2f}. "
                     f"Failed: {', '.join(x['gate'] for x in h['failed'])}.")
        elif r["gen"] in surv:
            x = surv[r["gen"]]
            extra = (f"\n\nON THE OTHER ISLAND'S FOLDS (data that never influenced it): win rate {100 * x['away_wr']:.1f}% (n = {x['away_n']}), "
                     f"alpha {x['away_alpha']:+.1f}, profit factor {x['away_pf']:.2f}.")
        try:
            src = compile_pine.export(g, {"compact": True, "generation": r["gen"], "name": f"SEH g{r['gen']}", "tier": "none (not certified)",
                                          "tag": f"SEH_G{r['gen']}", "win_rate_statement": statement(r, extra)})
        except Exception as e:
            r["note"] = f"not exported: {type(e).__name__}"
            failed += 1
            continue
        if static_audit.scan_pine(src):
            audit_hits += 1
            r["note"] = "not exported: static Pine audit hit"
            continue
        name = f"g{r['gen']:06d}_{r['tf']}min_wr{100 * r['wr']:.0f}_pf{r['pf']:.2f}_n{r['n']}.pine"
        p = part_of(r)
        if p not in zips:
            zips[p] = zipfile.ZipFile(os.path.join(OUT, "all_50pct", f"SEH_all_{p}.zip"), "w", zipfile.ZIP_DEFLATED, compresslevel=6)
        sub = "profitable_on_screening_folds" if r["pf"] > 1.0 else "unprofitable_on_screening_folds"
        zips[p].writestr(f"{sub}/{name}", src)
        counts[p] += 1
        r["file"] = f"all_50pct/SEH_all_{p}.zip:{sub}/{name}"
        if r["gen"] in tier:
            best.writestr(f"{tier[r['gen']]}/{name}", src)
            r["best_file"] = f"{tier[r['gen']]}/{name}"
            best_rows.append(r)
    cols = ["file", "generation", "timeframe_min", "win_rate", "twin_win_rate", "alpha_pts", "profit_factor", "trades", "trades_per_year",
            "score", "complexity", "status", "island", "rules", "note"]

    def row(r, file_key):
        return [r.get(file_key, ""), r["gen"], r["tf"], round(r["wr"], 4), round(r["wr"] - r["alpha"] / 100.0, 4), round(r["alpha"], 1), round(r["pf"], 3),
                r["n"], round(r["n"] / 2 / YEARS_HOME), round(r["score"], 4), r["cx"], r["status"], r["island"], one_line(r["g"]), r["note"]]

    with gzip.open(os.path.join(OUT, "SEH_INDEX_all_50pct.csv.gz"), "wt", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(cols)
        for r in rows:
            w.writerow(row(r, "file"))
    buf = io.StringIO()
    w = csv.writer(buf)
    w.writerow(cols)
    for r in sorted(best_rows, key=lambda r: (r["best_file"].split("/")[0], -r["score"])):
        w.writerow(row(r, "best_file"))
    best.writestr("SEH_INDEX.csv", buf.getvalue())
    tc = collections.Counter(r["best_file"].split("/")[0] for r in best_rows)
    contents = "\n".join([
        f"- `01_closest_to_passing/` ({tc['01_closest_to_passing']} files): passed the screen on their island's folds, then failed on all six "
        "folds. Each header gives the six-fold result and the gates it failed. Start here.",
        f"- `02_held_up_on_unseen_data/` ({tc['02_held_up_on_unseen_data']} files): leaders that kept at least half their score and a profit "
        "factor above 1.0 on the other island's folds. Each header gives that result.",
        "- `03_best_by_score_<timeframe>/` (" + ", ".join(f"{tc[k]} at {k[-5:-3]} min" for k in sorted(tc) if k.startswith("03")) +
        "): the highest composite scores after generation 20,008 (when the anti-overfitting changes were made), profitable on the "
        "screening folds, at least 150 trades.",
        "- `SEH_INDEX.csv`: one row per file."])
    all_exp = [r for r in exportable if r.get("file")]
    best.writestr("README.md", README.format(
        unprofitable=f"{sum(1 for r in all_exp if r['pf'] <= 1.0):,}", total=f"{len(all_exp):,}",
        contents=contents + f"\n\nThis curated archive holds {len(best_rows)} of them, all profitable on the screening folds, which is partly why "
                            "they were picked. The complete set is in the `SEH_all_*.zip` parts."))
    best.close()
    for p, z in zips.items():
        z.writestr("README.md", README.format(
            unprofitable=f"{sum(1 for r in all_exp if r['pf'] <= 1.0):,}", total=f"{len(all_exp):,}",
            contents=f"This is part `{p}` of the complete set: {counts[p]} strategies in two folders, `profitable_on_screening_folds/` and "
                     "`unprofitable_on_screening_folds/`. The full index of all parts is `SEH_INDEX_all_50pct.csv.gz`. For a short list worth "
                     "testing first, use `SEH_strategies_best.zip`."))
        z.close()
    summ = {"win_rate_50_or_more": len(rows), "exported": len(all_exp), "profitable_on_screening_folds": sum(1 for r in all_exp if r["pf"] > 1.0),
            "not_exported": dict(collections.Counter(r["note"].split(":")[1].strip().split(" to generation")[0] if r["note"] else "" for r in rows if r["note"])),
            "export_errors": failed, "static_audit_hits": audit_hits, "best_archive_files": len(best_rows), "best_by_tier": dict(tc),
            "parts": {p: {"files": counts[p], "MB": round(os.path.getsize(os.path.join(OUT, "all_50pct", f"SEH_all_{p}.zip")) / 1e6, 1)} for p in counts},
            "best_MB": round(os.path.getsize(os.path.join(OUT, "SEH_strategies_best.zip")) / 1e6, 2)}
    json.dump(summ, open(os.path.join(OUT, "SEH_export_summary.json"), "w"), indent=1)
    print(json.dumps(summ, indent=1))


if __name__ == "__main__":
    main()
